#!/bin/sh
# atts.sh: Rossler and Chua attractors (explicit Euler) -> stdout
T=/home/claude/work/tools/ex2vm
out() { # name steps_per_frame euler_body_file scale cx cy cz
printf '%s_frame:\n %%rep %s\n' "$1" "$2"
$T < "$3"
printf ' %%endrep\n'
$T <<EOT
t0 = (s0-$5)*$4
t1 = ((s2-$7)*0.6+(s1-$6)*0.8)*$4
t2 = ((s1-$6)*0.6-(s2-$7)*0.8)*$4
EOT
printf ' ROTV t0,t2,0.22\n ldv t0\n ldv t1\n ldv t2\n outxyz\n'
$T <<EOT
c = sat(s2*$8+abs(s0)*$9)
b = (0.75+0.25*sin(s3*40+t*2))*(1+0.5*h0)
EOT
printf ' o_end\n'
}
echo "; generated by atts.sh"
echo "section .data"
cat > /tmp/ros.txt <<EOT
t0 = s0+0.011*(-(s1+s2))
t1 = s1+0.011*(s0+0.2*s1)
t2 = s2+0.011*(0.2+s2*(s0-5.7))
s0 = t0
s1 = t1
s2 = t2
EOT
printf 'rossler_init:\n ATT_INIT 6.0,6.0,3.0\n'
out rossler 10 /tmp/ros.txt 0.17 0.0 0.0 6.0 0.04 0.02

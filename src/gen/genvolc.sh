#!/bin/sh
# genvolc.sh: volcans.ex -> volc.inc (macros H_NAME xx zz, via ex2vm)
T=/home/claude/work/tools/ex2vm
EX=$(dirname "$0")/volcans.ex
echo "; generated by genvolc.sh from volcans.ex"
echo "section .data"
cur=""
while IFS= read -r line; do
  case "$line" in
    "@"*) [ -n "$cur" ] && { "$T" < /tmp/vol_cur.txt; echo "%endmacro"; }
          cur=${line#@}; if [ "$cur" = HV ]; then echo "%macro HV 2"; else echo "%macro $cur 0"; fi; : > /tmp/vol_cur.txt ;;
    *) echo "$line" >> /tmp/vol_cur.txt ;;
  esac
done < "$EX"
"$T" < /tmp/vol_cur.txt; echo "%endmacro"

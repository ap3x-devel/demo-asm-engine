#!/bin/sh
# genrel.sh: reliefs.ex -> relief.inc (macros H_NAME xx zz, via ex2vm)
T=/home/claude/work/tools/ex2vm
EX=$(dirname "$0")/reliefs.ex
echo "; generated by genrel.sh from reliefs.ex"
echo "section .data"
cur=""
while IFS= read -r line; do
  case "$line" in
    "@"*) [ -n "$cur" ] && { "$T" < /tmp/rel_cur.txt; echo "%endmacro"; }
          cur=${line#@}; echo "%macro H_$cur 2"; : > /tmp/rel_cur.txt ;;
    *) echo "$line" >> /tmp/rel_cur.txt ;;
  esac
done < "$EX"
"$T" < /tmp/rel_cur.txt; echo "%endmacro"

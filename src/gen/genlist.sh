#!/bin/sh
# genlist.sh starts.txt scenes30.txt > list.inc : scene table (3 titles + N distinct scenes)
ST=$1; SC=$2
N=$(grep -vc '^#' "$SC")
echo "; generated by genlist.sh - do not edit (coder: Ivandoe)"
echo "%define SCN_N $((N+3))"
echo "scn_tab:"
cat <<'EOT'
; ---- titles: demo name, coder, musician (particle text over the alpine background)
 SCNR 0,0,2.0, 0.0,-6.0,12.0, 8.0,2.0
 BGL alpine,PAL_ALPINE,7.0,11,0.06
 F_TEXT 0,PAL_GOLD
 SCNR 1,32,2.5, 0.0,6.0,-12.0, 8.0,2.0
 BGL fjord,PAL_FJORD,7.0,11,0.06
 F_TEXT 1,PAL_DAWN
 SCNR 2,0,2.5, 0.0,-4.0,10.0, 8.0,2.0
 BGL hills,PAL_DAWN,7.0,11,0.15
 F_TEXT 2,PAL_STEEL
EOT
awk -v st="$ST" '
BEGIN{ i=0; while((getline l < st)>0){ split(l,a," "); o[i]=a[1]; r[i]=a[2]; i++ }
 cam[0]="-4.0,-10.0,8.0"; cam[1]="-2.5,6.0,-7.0"; cam[2]="-5.0,0.0,9.0"; cam[3]="-1.5,12.0,-6.0";
 amp["alpine"]=0.06;amp["fjord"]=0.06;amp["volcano"]=0.2;amp["canyon"]=0.2;amp["ocean"]=0.9;amp["dune"]=0.5;
 amp["ice"]=0.1;amp["terrace"]=0.2;amp["karst"]=0.1;amp["hills"]=0.15;amp["mesa"]=0.1;amp["ridges"]=0.2;
 amp["isles"]=0.5;amp["spires"]=0.1;amp["rings"]=0.3; k=0 }
/^#/ {next}
{ idx=k+3; printf "; ---- scene %d : order %d row %d : %s + %s\n",k+1,o[idx],r[idx],$1,$3;
  c=cam[k%4]; if($6!="" && $6!="-"){split(c,q,","); c=$6","q[2]","q[3]}; d=($7!="")?$7:"7.0"; printf " SCN %d,%d,%s,%s,%s\n",o[idx],r[idx],c,d,$5;
  printf " BGL %s,%s,7.0,%d,%s\n",$1,$2,11+7*(k+1),amp[$1];
  printf " F_%s %s,%d\n",$3,$4,3+5*(k+1); k++ }' "$SC"

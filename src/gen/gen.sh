#!/bin/sh
# gen.sh: objs5.ex -> obj5.inc (via ex2vm)
EX=$(dirname "$0")/objs5.ex; TOOL=$(dirname "$0")/../../../tools/ex2vm
[ -x "$TOOL" ] || TOOL=/home/claude/work/tools/ex2vm
echo "; generated by gen.sh from objs5.ex - do not edit"
echo "section .data"
cur=""
while IFS= read -r line; do
  case "$line" in
    "#"*|"") ;;
    "@"*) if [ -n "$cur" ]; then
            "$TOOL" < /tmp/ex_cur.txt
            printf ' ROTV t13,t15,0.19\n ldv t13\n kk 1.15\n o_mul\n ldv t14\n kk 1.15\n o_mul\n ldv t15\n kk 1.15\n o_mul\n outxyz\n ldv t11\n o_sat\n stv V_C\n ldv t12\n stv V_B\n o_end\n'
          fi
          cur=${line#@}; echo "${cur}_frame:"; : > /tmp/ex_cur.txt ;;
    *) echo "$line" >> /tmp/ex_cur.txt ;;
  esac
done < "$EX"
"$TOOL" < /tmp/ex_cur.txt
printf ' ROTV t13,t15,0.19\n ldv t13\n kk 1.15\n o_mul\n ldv t14\n kk 1.15\n o_mul\n ldv t15\n kk 1.15\n o_mul\n outxyz\n ldv t11\n o_sat\n stv V_C\n ldv t12\n stv V_B\n o_end\n'
